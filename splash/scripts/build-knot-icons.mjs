// Write the ring-knot icons (favicon and app icon) for each mode from one
// shape and one palette table, so the variants can't drift apart.
//
//   node scripts/build-knot-icons.mjs
//
// Writes public/icons/knot-ring-{light,dark,vibrant}.svg, plus knot-ring.svg,
// which follows the visitor's system light/dark setting on its own. The page
// then swaps to the site's chosen mode (see BaseLayout.astro).
// PNG app icons are made from these with scripts/build-knot-icons-png.sh.
//
// Colors mirror the modes in src/styles/theme.css: accent → thread for one
// ribbon, thread → accent-warm for the other, warm → thread → accent for the ring.

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(fileURLToPath(new URL('..', import.meta.url)), 'public', 'icons');

export const PALETTES = {
  light: { bg: '#f6f1e6', accent: '#1e1b4b', thread: '#b3196a', warm: '#d4900a' },
  dark: { bg: '#0c0c14', accent: '#5b6fff', thread: '#c8ff2e', warm: '#ffb84d' },
  vibrant: { bg: '#060612', accent: '#c8ff2e', thread: '#ec3a8c', warm: '#ffb84d' },
};

// The ring knot, at the proportions that hold up at 16px (design/knot-mark-square/07).
const shape = `
  <rect width="64" height="64" rx="14" class="bg"/>
  <circle cx="32" cy="32" r="26" stroke="url(#kr)" stroke-width="4.4"/>
  <g transform="translate(32 32) scale(0.86) translate(-32 -30)" stroke-width="5.8">
    <path d="M 12 32 C 12 18 24 14 32 22 C 40 30 52 30 52 18" stroke="url(#ka)"/>
    <path d="M 52 18 C 52 30 40 30 32 38 C 24 46 12 46 12 32" stroke="url(#ka)"/>
    <path d="M 12 18 C 12 30 24 30 32 22" stroke="url(#kb)"/>
    <path d="M 32 38 C 40 46 52 46 52 32 C 52 18 40 14 32 22" stroke="url(#kb)"/>
  </g>`;

const defs = `
  <defs>
    <linearGradient id="ka" x1="0" y1="0" x2="64" y2="64" gradientUnits="userSpaceOnUse">
      <stop offset="0%" class="accent"/><stop offset="100%" class="thread"/>
    </linearGradient>
    <linearGradient id="kb" x1="64" y1="0" x2="0" y2="64" gradientUnits="userSpaceOnUse">
      <stop offset="0%" class="thread"/><stop offset="100%" class="warm"/>
    </linearGradient>
    <linearGradient id="kr" x1="0" y1="64" x2="64" y2="0" gradientUnits="userSpaceOnUse">
      <stop offset="0%" class="warm"/><stop offset="50%" class="thread"/><stop offset="100%" class="accent"/>
    </linearGradient>
  </defs>`;

const rules = (p) =>
  `.bg { fill: ${p.bg} } .accent { stop-color: ${p.accent} } .thread { stop-color: ${p.thread} } .warm { stop-color: ${p.warm} }`;

const svg = (title, css) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" fill="none" stroke-linecap="round" stroke-linejoin="round">
  <title>${title}</title>
  <!-- Generated by scripts/build-knot-icons.mjs. Edit there, not here. -->
  <style>${css}</style>${defs}${shape}
</svg>
`;

mkdirSync(out, { recursive: true });
for (const [mode, p] of Object.entries(PALETTES)) {
  writeFileSync(join(out, `knot-ring-${mode}.svg`), svg(`astro-knots (${mode})`, rules(p)));
}
writeFileSync(
  join(out, 'knot-ring.svg'),
  svg('astro-knots', `${rules(PALETTES.light)} @media (prefers-color-scheme: dark) { ${rules(PALETTES.dark)} }`),
);
console.log(`build-knot-icons: ${Object.keys(PALETTES).length + 1} icons in public/icons/`);
